#pragma once

/*
 * Жизненный цикл подписки: письма в чат в те моменты, когда человек решает,
 * платить ли.
 *
 *   — за ~2 дня до конца пробной недели: что за неделю сделали его кошельки
 *     и что останется бесплатно;
 *   — в конце пробной недели: итог и вводная цена первого месяца на 48 часов;
 *   — через 14 и 30 дней без премиума: сколько сделок его кошельков он
 *     пропустил (только если они были — пустое письмо не шлём);
 *   — за 3 дня до конца оплаченного срока — каждому, кто платил (тарифы
 *     разовые, автопродления нет).
 *
 *   — сразу после первого открытия приложения: приветствие — сколько
 *     бесплатных дней подарено и что в приложении можно делать (welcomeTick,
 *     раз в минуту).
 *
 * Каждое письмо уходит человеку один раз: отметка в lifecycle_sent ставится
 * до отправки, так что два прохода подряд не продублируют сообщение.
 */

#include <string>

void initLifecycle();
// Проход раз в несколько минут из главного цикла бота.
void lifecycleTick();
// Приветствие получившим пробный Премиум — раз в минуту из главного цикла.
void welcomeTick();
// Письмо об окончании премиума — вызывает premium.cpp, когда срок истёк.
void sendPremiumEnded(const std::string& chatId);
