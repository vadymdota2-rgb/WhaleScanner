#pragma once

/* Оракул: скоринг монеты по всему, что бот успел собрать.
 *
 * Отличий от прежней линейной модели три.
 *
 * Первое — признаки. Их сорок семь вместо одиннадцати, и берутся они не
 * только из потока китов, но и из рынка: доходности за час, шесть и сутки,
 * реальная волатильность, ATR, расстояние до недельного максимума, RSI,
 * тренд к средней, MACD, фандинг и его отклонение от недельного, изменение
 * открытого интереса, перекос ликвидаций, режим биткоина, ширина рынка, час
 * суток, след события в рядах — давность листинга, всплеск объёма и сила
 * удара за последние часы, — и разметка ряда на колена: глубина отката,
 * близость к уровням Фибоначчи, длина текущего хода против предыдущего и
 * сколько колен подряд рынок идёт в одну сторону.
 * Чего нет в базе, берём у биржи: часовые свечи Hyperliquid с историей.
 *
 * Второе — модель. Градиентный бустинг на решающих деревьях вместо
 * логистической регрессии: линия не умеет сказать «приток помогает, но
 * только при низкой волатильности и отрицательном фандинге», а дерево умеет.
 *
 * Третье — честная оценка. Выборка делится по времени на три части: обучение,
 * проверка (ранняя остановка и калибровка) и тест, которого модель не видела
 * вовсе. Считаются AUC, логарифмические потери, точность и Брайер, и рядом —
 * то же самое у постоянного прогноза. Модель принимается, только если она
 * лучше него: иначе в бой идёт прежняя формула.
 *
 * Все признаки считаются одной функцией и только по данным на момент
 * события: и при обучении на журнале, и при живом счёте. Иначе модель учится
 * на будущем и в бою разваливается.
 */

#include <string>
#include <vector>

constexpr int ORACLE_NF = 47;

/* Горизонты, на которых учится модель. Шесть часов и сутки: исходы для обоих
   бот и так собирает, а какой из них подходит монете сейчас — решает сам
   оракул, сравнивая ожидаемый исход. */
constexpr long long ORACLE_H6 = 6 * 3600;
constexpr long long ORACLE_H24 = 86400;

/* Сколько размеченных исходов нужно, чтобы модель вообще могла быть принята.
 *
 * Обучение начинается раньше — с четырёхсот, — но принимать модель по такой
 * выборке нельзя. Тестовый кусок это 15% от неё: на шестистах примерах в нём
 * восемьдесят строк, и погрешность AUC там ±0.13. Измеренное на восьмидесяти
 * число 0.55 неотличимо ни от 0.42, ни от 0.68: ворота пропускали бы модель
 * без преимущества и заворачивали бы модель с ним.
 *
 * Тысяча двести берётся из складок скользящей проверки: каждая отдаёт под
 * проверку восьмую часть выборки, и при таком объёме это полтораста строк, а
 * не горстка. Идеальной эта цифра не делает ничего — доказать преимущество в
 * 0.55 на любых доступных нам объёмах нельзя, — но она убирает случай, когда
 * модель принимают по шуму. */
constexpr long long ORACLE_MIN_ACCEPT = 1200;
/* Сколько складок обязано отработать: меньше — и «проверено на нескольких
   отрезках» значит в разные дни разное. */
constexpr int ORACLE_WF_FOLDS = 4;

/* Приёмку переоценивают не по часам, а когда набралось заметно новых данных.
 *
 * Переобучение идёт раз в шесть часов, моделей четыре — это шестнадцать
 * попыток приёмки в сутки, и каждая независимый розыгрыш. При одном проценте
 * ложных срабатываний на попытку шанс принять модель без преимущества за
 * неделю — две трети, за месяц — почти единица. Никакие ворота этого не
 * переживут: в них просто стучатся, пока не откроется.
 *
 * Новые данные — новая проверка, а те же данные плюс двадцать строк — та же
 * проверка заново. Поэтому обучение вообще не запускается, пока с прошлой
 * попытки не набралось четверти выборки новых исходов.
 *
 * Считается именно новизна, а не размер выборки. Размером мерить нельзя:
 * журнал живёт окном в три месяца и рано или поздно выходит на полку —
 * сколько исходов приходит, столько и уходит. По росту выборки обучение в
 * этот день замерло бы навсегда, хотя данные за квартал сменились целиком.
 * По новизне оно идёт нон-стоп, но не чаще, чем данные успевают обновиться:
 * при полке в две тысячи исходов и сотне новых в сутки — раз в пять суток,
 * а не четырежды в день. */
constexpr int ORACLE_GROWTH_NUM = 5;    // новых исходов нужно
constexpr int ORACLE_GROWTH_DEN = 4;    // (5-4)/4 = четверть выборки

/* И даже прошедшую ворота модель не пускают с первого раза: она обязана
   пройти их дважды подряд, на данных, которых в первый раз ещё не было.
   Одно совпадение — не доказательство. */
constexpr int ORACLE_CONFIRMS = 2;

/* Во сколько раз обещанное может разойтись со сбывшимся сверх того, что даёт
   сама случайность.
 *
 * AUC говорит только про порядок: модель может безошибочно ранжировать и при
 * этом называть 90% там, где на деле 55%. Человеку показывают именно число, и
 * врущее число обесценивает весь экран.
 *
 * Сравнивается не с наперёд заданной величиной, а с шумовым полом: на
 * полутора сотнях тестовых строк даже идеально калиброванная модель даст
 * ошибку около восьми сотых просто от того, что доля в корзине гуляет.
 * Двойка — это «разошлось вдвое сильнее, чем могло бы случайно». */
constexpr double ORACLE_ECE_K = 2.0;

/* Поток китов по монете — то, что знает ai.cpp. Рыночную часть признаков
   оракул добирает сам по своим рядам. */
struct OracleInput {
    bool perp = false;
    std::string id;            // адрес токена или имя монеты
    long long buy = 0;
    long long sell = 0;
    int nBuy = 0;
    int nSell = 0;
    int wallets = 0;
    double oneShare = 0;       // доля самого крупного кошелька
    long long net6h = 0;
    long long netPrior = 0;
    long long funding = 0;     // наносы за час
    double liqUsd = 0;         // ликвидность пула, спот
    int levBp = 0;             // среднее плечо китов, базисные пункты
    long long liqLong = 0;     // вынесло лонгов
    long long liqShort = 0;    // вынесло шортов
    double topShare = 0;       // доля топ-100 в обороте
    double topDir = 0;         // -1 топ продаёт, +1 покупает
    int bothVenues = 0;
};

struct OracleVerdict {
    bool known = false;        // модели нет или признаков не хватило
    double pUp = 0.5;          // вероятность роста за горизонт
};

/* Куда модель ждёт хода цены за сутки — в долях от входа. Из этого строятся
   стоп и цели: не по вшитому множителю волатильности, а по тому, как далеко
   цена уходила в таких же условиях. */
struct OracleLevels {
    bool known = false;
    double up = 0;             // ожидаемый ход вверх
    double dn = 0;             // ожидаемый ход вниз
};

/* Почему модель так решила: признак и насколько он сдвинул вероятность.
   Считается подстановкой — признак заменяется срединным значением обучающей
   выборки, и разница показывает его вклад именно в эту строку, а не вообще. */
struct OracleReason {
    const char* name = "";
    double shift = 0;          // + помогает росту, − тянет вниз
};

struct OracleStats {
    long long horizon = 0;
    bool trained = false;
    /** Обучены ли леса уровней: стоп и цель от модели, а не от формулы. */
    bool levels = false;
    /** Средняя ошибка уровней на тесте, в процентах хода. */
    double upErr = 0;
    double dnErr = 0;
    long long at = 0;          // когда обучена
    long long samples = 0;     // всего размеченных исходов
    long long test = 0;        // из них в тесте
    int trees = 0;
    double auc = 0;            // на тесте
    double logloss = 0;
    double acc = 0;
    double brier = 0;
    double baseLogloss = 0;    // у постоянного прогноза
    double baseRate = 0;       // доля роста в тесте
    double wfAuc = 0;          // средний AUC на скользящей проверке
    /** Худшая складка: самое слабое доказательство, какое есть. Приёмка
     *  смотрит на него, потому что среднее скрывает «одна вытащила». */
    double wfWorst = 0;
    int wfFolds = 0;           // сколько складок отработало
    /** Насколько обещанное совпало со сбывшимся и сколько дала бы сама
     *  случайность при таких же корзинах. Приёмка смотрит на их отношение:
     *  голое число тут ни о чём не говорит. */
    double ece = 0;
    double eceFloor = 0;
    std::vector<std::pair<std::string, double>> top;  // вклад признаков
};

/* Час свечей и переобучение — зовётся из общего тика бота. */
void oracleTick();

/* Вероятность роста за 24 часа. known=false — модели нет, зовущий остаётся
   на формуле. */
OracleVerdict oracleScore(const OracleInput& in, long long asOf,
                          long long horizon = ORACLE_H24);

/* Что модель говорит про один горизонт: вероятность роста и ожидаемый ход в
   обе стороны. */
struct OracleView {
    long long horizon = 0;
    bool known = false;
    double pUp = 0.5;
    bool levels = false;
    double up = 0;
    double dn = 0;
};

/* Все горизонты разом — выбирать из них зовущему: решение зависит от того,
   какой план получается, а план строит он. */
std::vector<OracleView> oracleViews(const OracleInput& in, long long asOf);

/* Три признака, сильнее прочих сдвинувших эту оценку. Пусто, если модели
   нет: выдумывать причину к числу, которого не было, нельзя. */
std::vector<OracleReason> oracleWhy(const OracleInput& in, long long asOf,
                                    long long horizon = ORACLE_H24, int n = 3);

OracleLevels oracleLevels(const OracleInput& in, long long asOf,
                          long long horizon = ORACLE_H24);

OracleStats oracleStats(bool perp, long long horizon = ORACLE_H24);
bool oracleReady(bool perp, long long horizon = ORACLE_H24);

/* Имена признаков — для экрана состояния и для проверок. */
const char* oracleFeatureName(int i);
