#pragma once

/* Оракул: скоринг монеты по всему, что бот успел собрать.
 *
 * Отличий от прежней линейной модели три.
 *
 * Первое — признаки. Их 35 вместо одиннадцати, и берутся они не только из
 * потока китов, но и из рынка: доходности за час, шесть и сутки, реальная
 * волатильность, ATR, расстояние до недельного максимума, RSI, тренд к
 * средней, фандинг и его отклонение от недельного, изменение открытого
 * интереса, перекос ликвидаций, режим биткоина, ширина рынка, час суток.
 * Чего нет в базе, берём у биржи: часовые свечи Hyperliquid с историей.
 *
 * Второе — модель. Градиентный бустинг на решающих деревьях вместо
 * логистической регрессии: линия не умеет сказать «приток помогает, но
 * только при низкой волатильности и отрицательном фандинге», а дерево умеет.
 *
 * Третье — честная оценка. Выборка делится по времени на три части: обучение,
 * проверка (ранняя остановка и калибровка) и тест, которого модель не видела
 * вовсе. Считаются AUC, логарифмические потери, точность и Брайер, и рядом —
 * то же самое у постоянного прогноза. Модель принимается, только если она
 * лучше него: иначе в бой идёт прежняя формула.
 *
 * Все признаки считаются одной функцией и только по данным на момент
 * события: и при обучении на журнале, и при живом счёте. Иначе модель учится
 * на будущем и в бою разваливается.
 */

#include <string>
#include <vector>

constexpr int ORACLE_NF = 35;

/* Поток китов по монете — то, что знает ai.cpp. Рыночную часть признаков
   оракул добирает сам по своим рядам. */
struct OracleInput {
    bool perp = false;
    std::string id;            // адрес токена или имя монеты
    long long buy = 0;
    long long sell = 0;
    int nBuy = 0;
    int nSell = 0;
    int wallets = 0;
    double oneShare = 0;       // доля самого крупного кошелька
    long long net6h = 0;
    long long netPrior = 0;
    long long funding = 0;     // наносы за час
    double liqUsd = 0;         // ликвидность пула, спот
    int levBp = 0;             // среднее плечо китов, базисные пункты
    long long liqLong = 0;     // вынесло лонгов
    long long liqShort = 0;    // вынесло шортов
    double topShare = 0;       // доля топ-100 в обороте
    double topDir = 0;         // -1 топ продаёт, +1 покупает
    int bothVenues = 0;
};

struct OracleVerdict {
    bool known = false;        // модели нет или признаков не хватило
    double pUp = 0.5;          // вероятность роста за горизонт
};

/* Куда модель ждёт хода цены за сутки — в долях от входа. Из этого строятся
   стоп и цели: не по вшитому множителю волатильности, а по тому, как далеко
   цена уходила в таких же условиях. */
struct OracleLevels {
    bool known = false;
    double up = 0;             // ожидаемый ход вверх
    double dn = 0;             // ожидаемый ход вниз
};

/* Почему модель так решила: признак и насколько он сдвинул вероятность.
   Считается подстановкой — признак заменяется срединным значением обучающей
   выборки, и разница показывает его вклад именно в эту строку, а не вообще. */
struct OracleReason {
    const char* name = "";
    double shift = 0;          // + помогает росту, − тянет вниз
};

struct OracleStats {
    bool trained = false;
    /** Обучены ли леса уровней: стоп и цель от модели, а не от формулы. */
    bool levels = false;
    /** Средняя ошибка уровней на тесте, в процентах хода. */
    double upErr = 0;
    double dnErr = 0;
    long long at = 0;          // когда обучена
    long long samples = 0;     // всего размеченных исходов
    long long test = 0;        // из них в тесте
    int trees = 0;
    double auc = 0;            // на тесте
    double logloss = 0;
    double acc = 0;
    double brier = 0;
    double baseLogloss = 0;    // у постоянного прогноза
    double baseRate = 0;       // доля роста в тесте
    double wfAuc = 0;          // средний AUC на скользящей проверке
    std::vector<std::pair<std::string, double>> top;  // вклад признаков
};

/* Час свечей и переобучение — зовётся из общего тика бота. */
void oracleTick();

/* Вероятность роста за 24 часа. known=false — модели нет, зовущий остаётся
   на формуле. */
OracleVerdict oracleScore(const OracleInput& in, long long asOf);

/* Три признака, сильнее прочих сдвинувших эту оценку. Пусто, если модели
   нет: выдумывать причину к числу, которого не было, нельзя. */
std::vector<OracleReason> oracleWhy(const OracleInput& in, long long asOf, int n = 3);

OracleLevels oracleLevels(const OracleInput& in, long long asOf);

OracleStats oracleStats(bool perp);
bool oracleReady(bool perp);

/* Имена признаков — для экрана состояния и для проверок. */
const char* oracleFeatureName(int i);
