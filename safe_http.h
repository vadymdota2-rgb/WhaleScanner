/*
 * Запрос к чужому серверу, которому нельзя верить на слово (toncenter, Bot
 * API) — с пределами, которых нет у общего http() из rpc_client:
 *
 *   — только https; сертификат и имя сервера проверяются;
 *   — перенаправления (3xx) не выполняются и считаются сбоем: подменённый
 *     ответ не уведёт запрос на внутренний адрес или чужой сайт;
 *   — ответ длиннее maxBytes — сбой, а не обрезка (начало длинного ответа
 *     могло бы разобраться как правдоподобное), и память не растёт: читаем
 *     кусками и бросаем, как только предел перейдён;
 *   — сжатие не просим и сами не распаковываем («zip-бомба» не раскроется);
 *   — срок — на весь ответ, а не на каждый кусок: ответ «по байту» не держит
 *     поток часами.
 *
 * Пустая строка — сбой; причина — в error (для журнала, уже без управляющих
 * знаков). Проверки — tests/safe_http_test.py (настоящие локальные серверы:
 * http, чужой сертификат, перенаправление, огромный и медленный ответ).
 */

#include <cstddef>
#include <string>

/** Добавить кусок ответа, если общий размер не перейдёт max. false — перешёл
 *  (ничего не добавлено): запрос надо оборвать. */
[[nodiscard]] inline bool capAppend(std::string& to, const char* data, size_t n, size_t max) {
    if (n > max || to.size() > max - n) return false;
    to.append(data, n);
    return true;
}

